# -*- coding: utf-8 -*-
"""Build a pending independent-reader checklist from the current Exp4 schema.

Source availability, phrase presence and legal support are separate questions.
No library record or rubric is automatically assigned a verification level.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from validate_tasks import load_document, validate_document, match as match_case


def build_checklist(document, validation_report):
    if not validation_report.get('schema_valid'):
        raise ValueError('Cannot build a reader checklist from invalid task structure.')
    lines = [
        '<!-- GENERATED by build_reader_checklist.py -- do not edit by hand. -->',
        '', '# Experiment 4 — independent-reader checklist', '',
        'Status: **PENDING INDEPENDENT REVIEW. NOT READY FOR AN EXPERIMENT.**', '',
        'This frozen file is a blank, read-only template. Save completed findings in a separate review-response file that identifies this pack\'s manifest and hashes; do not fill or sign this file in place.', '',
        'Task structure: valid. Source checks: **' + validation_report['source_verification']['status'] + '**.',
        'A local phrase match establishes text presence only. It does not verify the cited paragraph, legal proposition, or the correctness of an answer key.',
        'Existing provenance statements below are declarations from the dataset. This checklist adds no verification level and grants no sign-off.', '',
        'Dataset: `' + document['dataset'] + '`',
        'Tasks: ' + str(validation_report['counts']['tasks']) + '; criteria: ' + str(validation_report['counts']['criteria']) + '.', '',
        '## Reviewer declaration', '',
        'Name: ____________________  Institution: ____________________',
        'Contact details: ____________________',
        'Hong Kong law qualification / relevant academic qualification: ____________________',
        'Qualification checked by / method / UTC time: ____________________',
        'Relevant subject experience and working language(s): ____________________',
        'Prior involvement in this library, builders, answer keys or experiments: ____________________',
        'Relationship to the project, funder, cited proceedings or model supplier: ____________________',
        'Model answers or experimental conditions seen: ____________________',
        'AI or research-assistance tools used in this review: ____________________',
        'Conflict status: [ ] pending assessment  [ ] no known conflict  [ ] disclosed and managed  [ ] recused',
        'Conflict assessor / decision / safeguards / UTC time: ____________________', '',
    ]
    if document.get('provenance'):
        lines += ['## Original dataset provenance declaration', '', str(document['provenance']), '']
    lines += ['## Outstanding source checks', '']
    issues = validation_report['source_verification']['issues']
    if issues:
        lines += ['- `' + x['path'] + '` — ' + x['code'] + ': ' + x['message'] for x in issues]
    else:
        lines += ['Local identity and phrase checks completed. Independent paragraph/proposition review remains pending.']
    for task in document['tasks']:
        lines += ['', '## ' + task['id'], '', 'As-of: `' + str(task['as_of']) + '` (a year denotes year-end).', '',
                  'Instruction:', '', task['instruction'], '', 'Matter files:']
        lines += ['- `' + filename + '`' for filename in task['files']]
        lines += ['', 'Recorded sources:', '',
                  '| Case or instrument | Citation | Court/publisher / source type | Legal date / available | Local check file | Official URL |',
                  '|---|---|---|---|---|---|']
        for source in task.get('sources', []):
            if source.get('decision_date'):
                legal_date = 'decision ' + source['decision_date']
            else:
                legal_date = 'version ' + source['version_date']
            availability = source['available_date']
            if source.get('availability_basis'):
                availability += '<br>' + source['availability_basis']
            lines += ['| ' + source['case'] + ' | ' + source['citation'] + ' | '
                      + source['court'] + ' / ' + source['source_type'] + ' | '
                      + legal_date + ' / ' + availability + ' | `'
                      + source['source_file'] + '` | ' + source['official_url'] + ' |']
        lines += ['', 'Requested connector payload:', '', '```json',
                  json.dumps(task['payload'], ensure_ascii=False, indent=2), '```', '']
        for criterion in task['rubric']:
            lines += ['### ' + criterion['id'], '', criterion['criterion'], '',
                      'Authority: ' + criterion['authority'], '', 'Pin: ' + criterion['pin'], '',
                      'Discriminates against: ' + criterion['discriminates_against'], '',
                      'Drift sensitive: ' + str(criterion['drift_sensitive']).lower() + '.',
                      'Recorded polarity: ' + criterion.get('polarity', 'not recorded; human review required') + '.', '',
                      'Per-source lexical checks: `' + json.dumps(criterion.get('source_checks', []), ensure_ascii=False) + '`', '',
                      '- [ ] Full party identity and every citation checked against the original source',
                      '- [ ] Original passage and the stated pin checked',
                      '- [ ] Court level and procedural nature (ratio / obiter / leave decision / separate reasons) checked',
                      '- [ ] Conditions, exceptions, factual limits, contrary authority and later treatment checked',
                      '- [ ] Passage supports this exact criterion at the stated cutoff',
                      '- [ ] Discriminator and any negative criterion checked',
                      'Source reading: [ ] official original  [ ] local extract  [ ] later decision quoting it  [ ] unavailable',
                      'Outcome: [ ] supports current text  [ ] rewrite and re-review required  [ ] unsupported  [ ] insufficient evidence  [ ] recused  [ ] not reviewed',
                      'Criterion conflict / recusal decision: ____________________',
                      'Reader: ____________________  Actual UTC time: ____________________',
                      'Signature or traceable approval record: ____________________',
                      'Finding / correction / withdrawal reason: ____________________', '']
    lines += ['## Independent sign-off', '',
              'Reader (did not write this library, matter files, builders or answer keys): ____________________',
              'Qualification verification completed by / method / UTC time: ____________________',
              'Final conflict status and safeguards: ____________________',
              '- [ ] Every criterion checked independently against the original source',
              '- [ ] Only `supports current text` outcomes are counted as passes',
              '- [ ] Missing source evidence and date limitations resolved or explicitly withdrawn',
              '- [ ] Any changed answer key rebuilt and rechecked in an isolated review copy',
              'Accepted criterion IDs: ____________________',
              'Rewritten / unsupported / excluded IDs: ____________________',
              'Open questions, owner and due date: ____________________',
              'Frozen review-pack SHA-256 / manifest reference: ____________________',
              'Completed response file / SHA-256: ____________________',
              'Reviewer signature: ____________________  Signed at (UTC): ____________________',
              '', 'This generated checklist deliberately leaves all human sign-offs blank.', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Build the Experiment 4 pending independent-reader checklist.')
    parser.add_argument('--tasks', type=Path, default=ROOT / 'tasks.json')
    parser.add_argument('--matter-dir', type=Path, default=ROOT / 'matter')
    parser.add_argument('--output', type=Path, default=ROOT / 'reader_checklist.md')
    args = parser.parse_args(argv)
    try:
        document = load_document(args.tasks)
        report = validate_document(document, args.matter_dir)
        if not report['schema_valid']:
            print(json.dumps(report, ensure_ascii=False, indent=2))
            return 1
        output = build_checklist(document, report)
        with open(args.output, 'w', encoding='utf-8', newline='\n') as stream:
            stream.write(output)
    except (OSError, UnicodeError, ValueError) as exc:
        print('Checklist not written: ' + str(exc), file=sys.stderr)
        return 1
    print('Wrote pending Experiment 4 checklist: ' + str(args.output))
    print('Source verification: ' + report['source_verification']['status'] + '; independent sign-off: pending.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
